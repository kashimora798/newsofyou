-- Phase 5 — memory 2.0.
-- ============================================================================
-- The twin already had `ai_memories` (Phase 5 of the old build): a flat list of
-- facts, written by hand or by one greedy LLM call that read 80 messages.
--
-- This migration turns that into a memory that behaves:
--
--   1. `ai_memories` grows the columns a memory needs — pinned, importance,
--      seen_count / last_seen_at (so a fact that keeps coming back rises),
--      archived, the day it came from and the message it came from.
--   2. `message_highlights` — the lines worth keeping from their own chat
--      (promises, plans, dates, firsts, feelings). Chosen by free heuristics in
--      the app, stored here, readable by both partners, writable only by the
--      service role.
--   3. `twin_nightly_runs` — an audit row per sweep, so the UI can say when the
--      memory was last fed and how much it cost.
--   4. RPCs: `twin_memory_upsert` (the single writer, dedupes), pin / forget,
--      a trigram `twin_memory_search` for prompts and the UI, stats, and the
--      material a nightly sweep needs (`twin_day_messages`, service-role only).
--
-- Idempotent: `add column if not exists`, `create table if not exists`,
-- `create or replace`. Nothing is dropped, `messages` is never written.
--
-- Cost: everything in this file is free. The only AI in Phase 5 is the nightly
-- sweep, which spends at most one `extract` call per run on the top ~5% of the
-- day's lines (see `twin-nightly`).

CREATE EXTENSION IF NOT EXISTS pg_trgm;

-- ── 1. ai_memories: the columns a memory needs ───────────────────────────
ALTER TABLE public.ai_memories ADD COLUMN IF NOT EXISTS pinned boolean NOT NULL DEFAULT false;
ALTER TABLE public.ai_memories ADD COLUMN IF NOT EXISTS archived boolean NOT NULL DEFAULT false;
ALTER TABLE public.ai_memories ADD COLUMN IF NOT EXISTS importance real NOT NULL DEFAULT 0.5;
ALTER TABLE public.ai_memories ADD COLUMN IF NOT EXISTS seen_count integer NOT NULL DEFAULT 1;
ALTER TABLE public.ai_memories ADD COLUMN IF NOT EXISTS last_seen_at timestamptz;
ALTER TABLE public.ai_memories ADD COLUMN IF NOT EXISTS updated_at timestamptz NOT NULL DEFAULT now();
ALTER TABLE public.ai_memories ADD COLUMN IF NOT EXISTS day date;
ALTER TABLE public.ai_memories ADD COLUMN IF NOT EXISTS message_id uuid;
ALTER TABLE public.ai_memories ADD COLUMN IF NOT EXISTS kind text;

CREATE INDEX IF NOT EXISTS idx_ai_memories_rank
  ON public.ai_memories (subject_user_id, pinned DESC, importance DESC, updated_at DESC);
CREATE INDEX IF NOT EXISTS idx_ai_memories_day
  ON public.ai_memories (day DESC) WHERE day IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_ai_memories_fact_trgm
  ON public.ai_memories USING gin (lower(fact) gin_trgm_ops);

-- ── 2. message_highlights: the lines worth keeping ───────────────────────
CREATE TABLE IF NOT EXISTS public.message_highlights (
  id          uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  message_id  uuid REFERENCES public.messages(id) ON DELETE SET NULL,
  user_id     uuid,                          -- who said it (their real author)
  day         date NOT NULL,
  kind        text NOT NULL DEFAULT 'other', -- promise|plan|date|feeling|first|gift|place|milestone|other
  text        text NOT NULL,
  score       real NOT NULL DEFAULT 0.5,
  source      text NOT NULL DEFAULT 'heuristic', -- heuristic|llm
  created_at  timestamptz NOT NULL DEFAULT now()
);

-- One row per (kind, line): a sweep can be re-run as often as you like.
CREATE UNIQUE INDEX IF NOT EXISTS uniq_message_highlights
  ON public.message_highlights (kind, md5(lower(text)));
CREATE INDEX IF NOT EXISTS idx_message_highlights_day
  ON public.message_highlights (day DESC, score DESC);

-- Both partners may read what the twin noticed; only the service role writes.
ALTER TABLE public.message_highlights ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "partners read highlights" ON public.message_highlights;
CREATE POLICY "partners read highlights" ON public.message_highlights
  FOR SELECT TO authenticated
  USING (public.is_partner(auth.uid()));
REVOKE ALL ON TABLE public.message_highlights FROM anon;
GRANT SELECT ON TABLE public.message_highlights TO authenticated;
GRANT ALL ON TABLE public.message_highlights TO service_role;

-- ── 3. twin_nightly_runs: what the sweeps cost ───────────────────────────

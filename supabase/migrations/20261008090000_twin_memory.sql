  facts_heuristic  integer NOT NULL DEFAULT 0,
  facts_llm        integer NOT NULL DEFAULT 0,
  llm_calls        integer NOT NULL DEFAULT 0,
  tokens           integer NOT NULL DEFAULT 0,

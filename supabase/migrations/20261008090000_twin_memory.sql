-- ── 10. Nightly bookkeeping ─────────────────────────────────────────────
CREATE OR REPLACE FUNCTION public.twin_nightly_log(
  p_days integer,
  p_highlights integer DEFAULT 0,
  p_facts_heuristic integer DEFAULT 0,
  p_facts_llm integer DEFAULT 0,
  p_llm_calls integer DEFAULT 0,
  p_tokens integer DEFAULT 0,
  p_note text DEFAULT NULL
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  saved public.twin_nightly_runs%ROWTYPE;
BEGIN
  INSERT INTO public.twin_nightly_runs (days, highlights, facts_heuristic, facts_llm, llm_calls, tokens, note)
  VALUES (greatest(coalesce(p_days, 7), 1), coalesce(p_highlights, 0), coalesce(p_facts_heuristic, 0),
          coalesce(p_facts_llm, 0), coalesce(p_llm_calls, 0), coalesce(p_tokens, 0), p_note)
  RETURNING * INTO saved;

  RETURN to_jsonb(saved);
END;
$$;
REVOKE ALL ON FUNCTION public.twin_nightly_log(integer, integer, integer, integer, integer, integer, text) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.twin_nightly_log(integer, integer, integer, integer, integer, integer, text) TO service_role;

-- Is a sweep allowed now? Free, so the client can ask cheaply before spending.
-- `p_force` is honoured for the owner only (a button in the control room).
CREATE OR REPLACE FUNCTION public.twin_nightly_state(p_force boolean DEFAULT false)
RETURNS jsonb
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  cfg public.twin_config%ROWTYPE;
  last_run public.twin_nightly_runs%ROWTYPE;
  mins numeric;
BEGIN
  IF NOT coalesce(public.is_partner(auth.uid()), false) THEN RETURN NULL; END IF;

  SELECT * INTO cfg FROM public.twin_config WHERE id = 1;
  SELECT * INTO last_run FROM public.twin_nightly_runs ORDER BY ran_at DESC LIMIT 1;

  mins := CASE WHEN last_run.ran_at IS NULL THEN NULL
               ELSE extract(epoch FROM (now() - last_run.ran_at)) / 60.0 END;

  RETURN jsonb_build_object(
    'allowed', coalesce(mins IS NULL OR mins >= 180 OR (p_force AND auth.uid() = cfg.owner_user_id), true),
    'reason', CASE WHEN mins IS NULL THEN 'never_run'
                   WHEN mins >= 180 THEN 'due'
                   ELSE 'too_soon' END
              || CASE WHEN p_force AND auth.uid() = cfg.owner_user_id THEN '+forced' ELSE '' END,
    'last_run_at', last_run.ran_at,
    'minutes_since', round(mins),
    'last_run', to_jsonb(last_run),
    'can_force', auth.uid() = cfg.owner_user_id
  );
END;
$$;
REVOKE ALL ON FUNCTION public.twin_nightly_state(boolean) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.twin_nightly_state(boolean) TO authenticated, service_role;


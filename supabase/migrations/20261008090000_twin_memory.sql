-- ── 4. The single writer for a fact ──────────────────────────────────────
-- Dedupes on the existing unique (subject_user_id, lower(fact)) index and keeps
-- the strongest version: it never overwrites a manual fact with an auto one,
-- never loses a pin, and counts how often the fact keeps showing up.
CREATE OR REPLACE FUNCTION public.twin_memory_upsert(
  p_subject uuid,
  p_fact text,
  p_category text DEFAULT 'other',
  p_source text DEFAULT 'auto',
  p_confidence real DEFAULT 0.6,
  p_importance real DEFAULT 0.5,
  p_day date DEFAULT NULL,
  p_message_id uuid DEFAULT NULL,
  p_kind text DEFAULT NULL,
  p_owner uuid DEFAULT NULL
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  clean text := left(btrim(regexp_replace(coalesce(p_fact, ''), '\s+', ' ', 'g')), 200);
  cat text := CASE WHEN p_category IN ('likes','dislikes','important','date','other') THEN p_category ELSE 'other' END;
  src text := CASE WHEN p_source = 'manual' THEN 'manual' ELSE 'auto' END;
  existing public.ai_memories%ROWTYPE;
  saved public.ai_memories%ROWTYPE;
BEGIN
  IF clean = '' OR length(clean) < 4 THEN
    RETURN jsonb_build_object('ok', false, 'reason', 'too_short');
  END IF;

  SELECT * INTO existing
  FROM public.ai_memories
  WHERE subject_user_id = p_subject AND lower(fact) = lower(clean)
  LIMIT 1;

  IF FOUND THEN
    UPDATE public.ai_memories SET
      seen_count   = seen_count + 1,
      last_seen_at = now(),
      updated_at   = now(),
      -- a human edit wins; auto may only raise importance, never lower it
      importance   = greatest(importance, coalesce(p_importance, importance)),
      confidence   = greatest(confidence, coalesce(p_confidence, confidence)),
      source       = CASE WHEN source = 'manual' THEN 'manual' ELSE src END,
      day          = coalesce(day, p_day),
      message_id   = coalesce(message_id, p_message_id),
      kind         = coalesce(kind, p_kind)
    WHERE id = existing.id
    RETURNING * INTO saved;

    RETURN jsonb_build_object('ok', true, 'action', 'seen', 'id', saved.id, 'seen_count', saved.seen_count);
  END IF;

  INSERT INTO public.ai_memories (
    owner_user_id, subject_user_id, fact, category, source, confidence,
    importance, day, message_id, kind, seen_count, last_seen_at
  ) VALUES (
    coalesce(p_owner, p_subject), p_subject, clean, cat, src, coalesce(p_confidence, 0.6),
    coalesce(p_importance, 0.5), p_day, p_message_id, p_kind, 1, now()
  )
  RETURNING * INTO saved;

  RETURN jsonb_build_object('ok', true, 'action', 'inserted', 'id', saved.id);
END;
$$;
REVOKE ALL ON FUNCTION public.twin_memory_upsert(uuid, text, text, text, real, real, date, uuid, text, uuid) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.twin_memory_upsert(uuid, text, text, text, real, real, date, uuid, text, uuid) TO service_role;

-- ── 5. pin / forget: either partner, never the AI alone ──────────────────
CREATE OR REPLACE FUNCTION public.twin_memory_pin(p_id uuid, p_pinned boolean DEFAULT true)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  touched int;
BEGIN
  IF NOT public.is_partner(auth.uid()) THEN RAISE EXCEPTION 'Not a participant'; END IF;

  UPDATE public.ai_memories
     SET pinned = coalesce(p_pinned, true),
         importance = CASE WHEN coalesce(p_pinned, true) THEN 1.0 ELSE importance END,
         updated_at = now()
   WHERE id = p_id;
  GET DIAGNOSTICS touched = ROW_COUNT;

  RETURN jsonb_build_object('ok', touched > 0, 'pinned', coalesce(p_pinned, true));
END;
$$;
REVOKE ALL ON FUNCTION public.twin_memory_pin(uuid, boolean) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.twin_memory_pin(uuid, boolean) TO authenticated, service_role;

CREATE OR REPLACE FUNCTION public.twin_memory_forget(p_id uuid)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  touched int;
BEGIN
  IF NOT public.is_partner(auth.uid()) THEN RAISE EXCEPTION 'Not a participant'; END IF;

  DELETE FROM public.ai_memories WHERE id = p_id;
  GET DIAGNOSTICS touched = ROW_COUNT;

  RETURN jsonb_build_object('ok', touched > 0, 'forgotten', touched);
END;
$$;
REVOKE ALL ON FUNCTION public.twin_memory_forget(uuid) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.twin_memory_forget(uuid) TO authenticated, service_role;

-- ── 6. search: what the twin should remember right now ───────────────────
-- Trigram-first, so it works with no embeddings at all. Pinned facts always
-- come first, then the closest match, then importance. `p_query` may be NULL
-- (then it is simply "the most important things").
CREATE OR REPLACE FUNCTION public.twin_memory_search(
  p_query text DEFAULT NULL,
  p_subject uuid DEFAULT NULL,
  p_limit integer DEFAULT 8
)
RETURNS TABLE (
  id uuid, fact text, category text, source text,
  confidence real, importance real, pinned boolean, sim real, day date
)
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  WITH q AS (SELECT nullif(btrim(coalesce(p_query, '')), '') AS t)
  SELECT m.id, m.fact, m.category, m.source, m.confidence, m.importance, m.pinned,
         CASE
           WHEN (SELECT t FROM q) IS NULL THEN 0::real
           ELSE greatest(similarity(m.fact, (SELECT t FROM q)),
                         word_similarity((SELECT t FROM q), m.fact))::real
         END AS sim,
         m.day
  FROM public.ai_memories m
  WHERE NOT m.archived
    AND (p_subject IS NULL OR m.subject_user_id = p_subject)
    AND (
      (SELECT t FROM q) IS NULL
      OR m.fact % (SELECT t FROM q)
      OR word_similarity((SELECT t FROM q), m.fact) > 0.2
      OR m.pinned
    )
  ORDER BY m.pinned DESC, sim DESC, m.importance DESC, m.updated_at DESC
  LIMIT greatest(coalesce(p_limit, 8), 1);
$$;
REVOKE ALL ON FUNCTION public.twin_memory_search(text, uuid, integer) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.twin_memory_search(text, uuid, integer) TO authenticated, service_role;

-- ── 7. stats, for the control room ──────────────────────────────────────
CREATE OR REPLACE FUNCTION public.twin_memory_stats()
RETURNS jsonb
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT jsonb_build_object(
    'total',        (SELECT count(*) FROM public.ai_memories WHERE NOT archived),
    'pinned',       (SELECT count(*) FROM public.ai_memories WHERE pinned AND NOT archived),
    'manual',       (SELECT count(*) FROM public.ai_memories WHERE source = 'manual' AND NOT archived),
    'auto',         (SELECT count(*) FROM public.ai_memories WHERE source = 'auto' AND NOT archived),
    'highlights',   (SELECT count(*) FROM public.message_highlights),
    'highlights_7d',(SELECT count(*) FROM public.message_highlights WHERE day > current_date - 7),
    'last_run',     (SELECT to_jsonb(r) FROM public.twin_nightly_runs r ORDER BY ran_at DESC LIMIT 1)
  )
  WHERE public.is_partner(auth.uid());
$$;
REVOKE ALL ON FUNCTION public.twin_memory_stats() FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.twin_memory_stats() TO authenticated, service_role;

-- ── 8. The material a sweep needs ───────────────────────────────────────
-- One day of real lines, mechanical rows and placeholders already removed.
-- Service role only: this is raw chat, the app reads its own copy through RLS.
CREATE OR REPLACE FUNCTION public.twin_day_messages(p_day date)
RETURNS TABLE (
  id uuid, user_id uuid, username text, content text, message_type text, created_at timestamptz
)
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT m.id, m.user_id, m.username, m.content, m.message_type, m.created_at
  FROM public.messages m
  WHERE (m.created_at AT TIME ZONE 'Asia/Kolkata')::date = p_day
    AND NOT public.twin_is_ignored_message(m.message_type)
    AND NOT public.twin_is_placeholder_content(m.content)
  ORDER BY m.created_at ASC;
$$;
REVOKE ALL ON FUNCTION public.twin_day_messages(date) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.twin_day_messages(date) TO service_role;

